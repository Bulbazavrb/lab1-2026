# # 1. Введення даних користувачем та валідація
# Лабораторна робота № 1
# Варіант 12: Розрахунок вартості покупки з урахуванням знижки

# ==========================================
# 1. Введення даних з валідацією на помилки
# ==========================================

while True:
    try:
        # Отримуємо значення від користувача у вигляді тексту та приводимо до float
        purchase_amount = float(input("Введіть суму покупки (грн): "))

        # Перевірка бізнес-логіки: сума покупки не може бути меншою за нуль
        if purchase_amount < 0:
            raise ValueError("Сума покупки не може бути від'ємною.")

        # Якщо помилок немає, виходимо з нескінченного циклу введення
        break
    except ValueError as e:
        # Перехоплюємо винятки при некоректному вводі (текст замість цифр або від'ємне число)
        print(f"Помилка: {e} Будь ласка, спробуйте ще раз.\n")

# ==========================================
# 2. Визначення розміру знижки за шкалою
# ==========================================

# Встановлюємо відсоток знижки залежно від величини чека
if purchase_amount >= 5000:
    discount_percent = 15
elif purchase_amount >= 2000:
    discount_percent = 10
elif purchase_amount >= 1000:
    discount_percent = 5
else:
    discount_percent = 0

# ==========================================
# 3. Арифметичні розрахунки
# ==========================================

# Обчислення грошового еквіваленту знижки
discount_amount = purchase_amount * (discount_percent / 100)

# Обчислення фінальної вартості до сплати
final_amount = purchase_amount - discount_amount

# 4. Форматоване виведення результатів

# Використовуємо форматовані f-рядки та специфікатор :.2f для округлення до копійок
print("\n" + "=" * 35)
print("       РЕЗУЛЬТАТИ РОЗРАХУНКУ       ")
print("=" * 35)
print(f"Початкова сума покупки : {purchase_amount:>10.2f} грн")
print(f"Відсоток знижки        : {discount_percent:>10}%")
print(f"Сума наданої знижки    : {discount_amount:>10.2f} грн")
print("-" * 35)
print(f"Кінцева вартість       : {final_amount:>10.2f} грн")
print("=" * 35)

# ==========================================
# 5. Додаткова інформація для користувача
# ==========================================

if discount_percent > 0:
    print(f"Економія: Ви заощадили {discount_amount:.2f} грн завдяки знижці!")
else:
    print("Порада: Зробіть покупку від 1000.00 грн, щоб отримати знижку від 5%.")

